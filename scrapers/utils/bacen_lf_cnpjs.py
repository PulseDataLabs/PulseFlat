def cnpj8_to_cnpj14(c8: str) -> str:
    """Converte a raiz do CNPJ de 8 dígitos para o CNPJ matriz de 14 posições (RRRRRRRR0001DV)."""
    digits = re.sub(r"\D", "", str(c8 or ""))
    if not digits:
        return ""
    if len(digits) == 14:
        return digits
    root = digits.zfill(8)[:8]
    base = root + "0001"
    w1 = [5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]
    s1 = sum(int(d) * w for d, w in zip(base, w1))
    r1 = s1 % 11
    d1 = 0 if r1 < 2 else 11 - r1
    base2 = base + str(d1)
    w2 = [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]
    s2 = sum(int(d) * w for d, w in zip(base2, w2))
    r2 = s2 % 11
    d2 = 0 if r2 < 2 else 11 - r2
    return base2 + str(d2)


def strip_accents(s: str) -> str:
    norm = unicodedata.normalize("NFKD", str(s or "").upper())
    return "".join(c for c in norm if not unicodedata.combining(c))


def norm_exact(s: str) -> str:
    s = strip_accents(s)
    s = re.sub(r"\s*-\s*PRUDENCIAL\b", "", s)
    s = re.sub(r"[^A-Z0-9 ]", " ", s)
    return " ".join(s.split())


def norm_nosuffix(s: str) -> str:
    s = norm_exact(s)
    s = re.sub(r"\bBCO\b", "BANCO", s)
    s = re.sub(r"\b(S A|SA|LTDA|BM|CFI|SCFI|BCO MULTIPLO|BANCO MULTIPLO)\b", " ", s)
    return " ".join(s.split())


