_NOSUFFIX_MAP: dict[str, str] = {}
_PREFIX35_MAP: dict[str, str] = {}
_DYNAMIC_LOADED = False


def _ensure_indexes() -> None:
    if _NOSUFFIX_MAP:
        return
    for k, c14 in EMISSOR_CNPJ14_MAP.items():
        ns = norm_nosuffix(k)
        if ns:
            _NOSUFFIX_MAP.setdefault(ns, c14)
        if len(k) >= 30:
            _PREFIX35_MAP.setdefault(k[:33].strip(), c14)


def _register_dynamic(raw_name: str, c8_or_14: str) -> None:
    if not raw_name or not c8_or_14:
        return
    c14 = cnpj8_to_cnpj14(c8_or_14)
    if len(c14) != 14:
        return
    n = norm_exact(raw_name)
    if not n or (c14.startswith("00000000") and "BRASIL" not in n and n != "BB"):
        return
    EMISSOR_CNPJ14_MAP.setdefault(n, c14)
    ns = norm_nosuffix(raw_name)
    if ns:
        _NOSUFFIX_MAP.setdefault(ns, c14)
    if len(n) >= 30:
        _PREFIX35_MAP.setdefault(n[:33].strip(), c14)


def _load_dynamic_fallback() -> None:
    global _DYNAMIC_LOADED
    if _DYNAMIC_LOADED:
        return
    _DYNAMIC_LOADED = True
    _ensure_indexes()

    cad_path = Path("data/bacen_cadastro_instituicoes.csv.gz")
    if cad_path.exists():
        try:
            with gzip.open(cad_path, "rt", encoding="utf-8") as f:
                for row in csv.DictReader(f):
                    c8 = (row.get("cnpj_instituicao_lider") or "").strip()
                    cod = (row.get("codigo_instituicao") or "").strip()
                    if not c8.isdigit() and cod.isdigit() and len(cod) <= 8:
                        c8 = cod.zfill(8)
                    if c8:
                        _register_dynamic(row.get("nome_instituicao", ""), c8)
        except Exception:
            pass

    cong_path = Path("data/bacen_conglomerados.csv")
    if cong_path.exists():
        try:
            with cong_path.open("r", encoding="utf-8") as f:
                for row in csv.DictReader(f):
                    c8 = re.sub(r"\D", "", row.get("CNPJ PARTICIPANTE", ""))
                    if c8 and c8 != "00000000" and row.get("TIPO PARTICIPAÇÃO") == "LIDER":
                        _register_dynamic(row.get("NOME DO CONGLOMERADO", ""), c8)
                        _register_dynamic(row.get("NOME DO PARTICIPANTE", ""), c8)
        except Exception:
            pass

    for ym in ("202512", "202412"):
        url = (
            "https://olinda.bcb.gov.br/olinda/servico/IFDATA/versao/v1/odata/"
            f"IfDataCadastro(AnoMes=@AnoMes)?@AnoMes={ym}&$format=json"
        )
        try:
            resp = requests.get(url, headers={"User-Agent": "Mozilla/5.0"}, timeout=15)
            if resp.status_code == 200:
                for item in resp.json().get("value", []):
                    c_lider = re.sub(r"\D", "", str(item.get("CnpjInstituicaoLider") or ""))
                    c_cod = re.sub(r"\D", "", str(item.get("CodInst") or ""))
                    c8 = c_lider.zfill(8) if c_lider else (c_cod.zfill(8) if len(c_cod) <= 8 and c_cod.isdigit() else "")
                    if len(c8) == 8:
                        for k in ("NomeInstituicao", "NomeConglomeradoPrudencial", "NomeConglomeradoFinanceiro"):
                            if item.get(k):
                                _register_dynamic(item[k], c8)
        except Exception:
            pass


def resolve_emissor_cnpj14(nome: str) -> str:
    """Resolve o nome de uma IF, cooperativa ou conglomerado do BCB para o CNPJ de 14 posições."""
    if not nome:
        return ""
    _ensure_indexes()
    n = norm_exact(nome)
    if n in EMISSOR_CNPJ14_MAP:
        return EMISSOR_CNPJ14_MAP[n]
    ns = norm_nosuffix(nome)
    if ns in _NOSUFFIX_MAP:
        return _NOSUFFIX_MAP[ns]
    if len(n) >= 33 and n[:33].strip() in _PREFIX35_MAP:
        return _PREFIX35_MAP[n[:33].strip()]

    _load_dynamic_fallback()
    if n in EMISSOR_CNPJ14_MAP:
        return EMISSOR_CNPJ14_MAP[n]
    if ns in _NOSUFFIX_MAP:
        return _NOSUFFIX_MAP[ns]
    if len(n) >= 33 and n[:33].strip() in _PREFIX35_MAP:
        return _PREFIX35_MAP[n[:33].strip()]

    raw_up = strip_accents(nome)
    for sep in (" - ", " – ", " -", "- "):
        if sep in raw_up:
            after = norm_exact(raw_up.split(sep)[-1])
            if after in EMISSOR_CNPJ14_MAP:
                return EMISSOR_CNPJ14_MAP[after]
            after_ns = norm_nosuffix(after)
            if after_ns in _NOSUFFIX_MAP:
                return _NOSUFFIX_MAP[after_ns]
    return ""
